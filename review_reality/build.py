"""Rebuild everything from the raw files:  python -m review_reality.build

1. Load the three raw CSV files.
2. Clean them (clean.py).
3. Save the result to data/processed/reviews.db (SQLite).
4. Write docs/DATA_QUALITY.md with the real counts, so the documentation
   always matches the data instead of being typed by hand.
"""
from review_reality.clean import clean_reviews
from review_reality.db import query, write_database
from review_reality.load import load_all_raw
from review_reality.paths import DB_PATH, DOCS_DIR


def _table(df):
    """Format a DataFrame as a Markdown table (without extra libraries)."""
    header = "| " + " | ".join(map(str, df.columns)) + " |"
    divider = "|" + "|".join("---" for _ in df.columns) + "|"
    rows = ["| " + " | ".join("" if v != v else str(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join([header, divider, *rows])


def write_quality_report(raw, clean, steps):
    lines = ["# Data quality report", "", "_Generated by `python -m review_reality.build`. Do not edit by hand._", ""]

    lines += ["## Cleaning steps", "", "| Step | Rows |", "|---|---|"]
    lines += [f"| {name} | {count:,} |" for name, count in steps]

    missing = (raw.isna().mean() * 100).round(1).rename("pct_missing_raw").reset_index()
    missing.columns = ["column", "% missing (raw)"]
    lines += ["", "## Missing values in the raw data", "", _table(missing)]

    clean_missing = clean[["review_date", "recommends", "helpful_votes", "reviewer_id"]].isna().sum()
    lines += ["", "## Missing values after cleaning (kept, shown as blank)", "",
              _table(clean_missing.rename("missing").reset_index().rename(columns={"index": "column"}))]

    sites = clean["source_site"].value_counts().rename("reviews").reset_index()
    lines += ["", "## Where the reviews were collected", "", _table(sites)]

    lines += ["", "## Star ratings (all products)", "", _table(query("rating_distribution", {"family": None}))]
    lines += ["", "## Product families", "", _table(query("product_summary", {"min_reviews": 1}))]

    path = DOCS_DIR / "DATA_QUALITY.md"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def main():
    raw = load_all_raw()
    clean, steps = clean_reviews(raw)
    write_database(clean)
    report = write_quality_report(raw, clean, steps)
    for name, count in steps:
        print(f"{name}: {count:,}")
    print(f"Database: {DB_PATH}")
    print(f"Report:   {report}")


if __name__ == "__main__":
    main()
