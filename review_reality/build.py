"""Rebuild everything from the raw files:  python -m review_reality.build

1. Load the three raw CSV files.
2. Clean them (clean.py).
3. Save the result to data/processed/reviews.db (SQLite).
4. Run the analytics (analytics.py) and save their tables to the same database.
5. Write docs/DATA_QUALITY.md and docs/ANALYSIS_RESULTS.md with the real
   numbers, so the documentation always matches the data instead of being typed by hand.
"""
import pandas as pd

from review_reality import analytics
from review_reality.analytics import COMPLAINT_THRESHOLD
from review_reality.clean import clean_reviews
from review_reality.db import query, write_analytics, write_database
from review_reality.load import load_all_raw
from review_reality.paths import DB_PATH, DOCS_DIR


def _table(df):
    """Format a DataFrame as a Markdown table (without extra libraries)."""
    header = "| " + " | ".join(map(str, df.columns)) + " |"
    divider = "|" + "|".join("---" for _ in df.columns) + "|"
    rows = ["| " + " | ".join("" if v != v else str(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join([header, divider, *rows])


def write_quality_report(raw, clean, steps):
    lines = ["# Data quality report", "", "_Generated by `python -m review_reality.build`. Do not edit by hand._", ""]

    lines += ["## Cleaning steps", "", "| Step | Rows |", "|---|---|"]
    lines += [f"| {name} | {count:,} |" for name, count in steps]

    missing = (raw.isna().mean() * 100).round(1).rename("pct_missing_raw").reset_index()
    missing.columns = ["column", "% missing (raw)"]
    lines += ["", "## Missing values in the raw data", "", _table(missing)]

    clean_missing = clean[["review_date", "recommends", "helpful_votes", "reviewer_id"]].isna().sum()
    lines += ["", "## Missing values after cleaning (kept, shown as blank)", "",
              _table(clean_missing.rename("missing").reset_index().rename(columns={"index": "column"}))]

    sites = clean["source_site"].value_counts().rename("reviews").reset_index()
    lines += ["", "## Where the reviews were collected", "", _table(sites)]

    lines += ["", "## Star ratings (all products)", "", _table(query("rating_distribution", {"family": None}))]
    lines += ["", "## Product families", "", _table(query("product_summary", {"min_reviews": 1}))]

    path = DOCS_DIR / "DATA_QUALITY.md"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def write_results_report(tables):
    """Write docs/ANALYSIS_RESULTS.md: model test scores and the main calculated tables."""
    lines = ["# Analysis results", "", "_Generated by `python -m review_reality.build`. Do not edit by hand._", ""]
    lines += ["## Text model test scores (20% of reviews held out)", "", _table(tables["model_metrics"])]

    summary = query("product_summary", {"min_reviews": 300})
    lines += ["", "## Products with at least 300 reviews", "", _table(summary)]

    lines += ["", f"## Most complained-about aspects (complaint = sentence scored >= {COMPLAINT_THRESHOLD} negative)", ""]
    for family in summary["family"]:
        aspects = query("aspect_summary", {"family": family, "threshold": COMPLAINT_THRESHOLD}).head(5)
        lines += [f"### {family}", "", _table(aspects), ""]

    bursts = query("review_bursts", {"family": None, "min_reviews": 20, "min_ratio": 5})
    mismatches = query("rating_text_mismatch", {"family": None, "high": 0.9, "low": 0.1})
    lines += [
        "## Unusual patterns (worth checking, not proof of fake reviews)",
        "",
        "| Pattern | Count |",
        "|---|---|",
        f"| Near-identical review pairs by different reviewer names | {len(tables['similar_pairs'])} |",
        f"| Review bursts (20+ reviews and 5x the product's typical day) | {len(bursts)} |",
        f"| Star/text mismatches (4-5 stars with text >= 0.9 negative, or 1-2 stars with text <= 0.1) | {len(mismatches)} |",
    ]
    path = DOCS_DIR / "ANALYSIS_RESULTS.md"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def main():
    raw = load_all_raw()
    clean, steps = clean_reviews(raw)
    write_database(clean)
    quality_report = write_quality_report(raw, clean, steps)
    for name, count in steps:
        print(f"{name}: {count:,}")

    print("Running analytics (text model, aspects, similar reviews)...")
    tables = analytics.run_all(clean)
    tables["build_steps"] = pd.DataFrame(steps, columns=["step", "rows"])
    write_analytics(tables)
    results_report = write_results_report(tables)

    print(f"Database: {DB_PATH}")
    print(f"Reports:  {quality_report}\n          {results_report}")


if __name__ == "__main__":
    main()
